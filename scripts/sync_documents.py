#!/usr/bin/env python3
"""Render GitHub-readable Markdown mirrors of repository DOCX files.

Python 3.10+ standard library only. DOCX remains the editorial source.
Unsupported content raises an error instead of silently disappearing.
"""
from __future__ import annotations

import argparse
import hashlib
import html
from pathlib import Path
import re
import sys
from urllib.parse import quote
import xml.etree.ElementTree as ET
import zipfile

W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
NS = {'w': W}
MARKER = '<!-- GENERATED by scripts/sync_documents.py; '
MONOSPACE = {'consolas', 'courier new', 'courier', 'cascadia code'}


class UnsupportedContent(ValueError):
    pass


def tag(name: str) -> str:
    return f'{{{W}}}{name}'


def escape(text: str) -> str:
    text = html.escape(text, quote=False)
    return re.sub(r'([\\`*_\[\]])', r'\\\1', text)


def plain(node: ET.Element) -> str:
    out = []
    for child in node.iter():
        if child.tag == tag('t'):
            out.append(child.text or '')
        elif child.tag == tag('tab'):
            out.append('\t')
        elif child.tag == tag('br') and child.get(tag('type')) != 'page':
            out.append('\n')
        elif child.tag == tag('cr'):
            out.append('\n')
    return ''.join(out)


def enabled(node: ET.Element | None) -> bool:
    return node is not None and node.get(tag('val'), 'true') not in {'0', 'false', 'off'}


def format_run(run: ET.Element, decorate: bool = True) -> str:
    text = plain(run)
    if not text:
        return ''
    # Word often keeps the following separator space inside a bold run.
    match = re.fullmatch(r'(\s*)(.*?)(\s*)', text, re.S)
    lead, core, trail = match.groups()
    core = escape(core)
    props = run.find('w:rPr', NS)
    if core and decorate and props is not None:
        if enabled(props.find('w:b', NS)):
            core = '**' + core + '**'
        if enabled(props.find('w:i', NS)):
            core = '*' + core + '*'
    return escape(lead) + core + escape(trail)


def inline(node: ET.Element, relationships: dict[str, str], decorate: bool = True) -> str:
    out = []
    for child in node:
        if child.tag == tag('r'):
            out.append(format_run(child, decorate))
        elif child.tag == tag('hyperlink'):
            label = inline(child, relationships, decorate)
            rid = child.get(f'{{{R}}}id')
            anchor = child.get(tag('anchor'))
            target = relationships.get(rid) if rid else ('#' + anchor if anchor else None)
            if not target:
                raise UnsupportedContent('Hyperlink has no resolvable target')
            target = target.replace(' ', '%20').replace('(', '%28').replace(')', '%29')
            out.append(f'[{label}]({target})')
        elif child.tag in {tag('pPr'), tag('bookmarkStart'), tag('bookmarkEnd'),
                           tag('proofErr'), tag('lastRenderedPageBreak')}:
            continue
        elif plain(child):
            raise UnsupportedContent(f'Unsupported paragraph content: {child.tag}')
    return ''.join(out)


def style(p: ET.Element) -> str:
    value = p.find('w:pPr/w:pStyle', NS)
    return value.get(tag('val'), '') if value is not None else ''


def is_code(p: ET.Element) -> bool:
    if style(p).lower() in {'code', 'sourcecode'}:
        return True
    fonts = [value.lower() for node in p.findall('.//w:rFonts', NS)
             for value in node.attrib.values()]
    return any(font in MONOSPACE for font in fonts)


def paragraph(p: ET.Element, rels: dict[str, str], in_cell: bool = False) -> str:
    raw = plain(p)
    if not raw.strip():
        return ''
    if is_code(p):
        if in_cell:
            raise UnsupportedContent('Code in a table cell needs a reviewed conversion')
        fence = '`' * max(3, max((len(m.group()) + 1 for m in re.finditer(r'`+', raw)), default=3))
        return f'{fence}python\n{raw}\n{fence}'
    st = style(p)
    text = inline(p, rels, decorate=not (st == 'Title' or st.startswith('Heading'))).strip()
    if in_cell:
        return text.replace('\n', '<br>')
    if st == 'Title':
        return '# ' + text
    match = re.fullmatch(r'Heading(\d+)', st)
    if match:
        return '#' * min(int(match.group(1)) + 1, 6) + ' ' + text
    if st.startswith('ListBullet'):
        return '- ' + text
    if st.startswith('ListNumber'):
        raise UnsupportedContent('Automatic numbered lists need explicit numbering support')
    return text.replace('\n', '  \n')


def table(tbl: ET.Element, rels: dict[str, str]) -> str:
    rows = []
    for row in tbl.findall('w:tr', NS):
        cells = []
        for cell in row.findall('w:tc', NS):
            blocks = [paragraph(p, rels, in_cell=True) for p in cell.findall('w:p', NS)]
            cells.append('<br><br>'.join(b for b in blocks if b).replace('|', '\\|'))
        rows.append(cells)
    if not rows or not rows[0]:
        return ''
    if any(len(row) != len(rows[0]) for row in rows):
        raise UnsupportedContent('Nonrectangular table')
    output = ['| ' + ' | '.join(rows[0]) + ' |', '| ' + ' | '.join(['---'] * len(rows[0])) + ' |']
    output.extend('| ' + ' | '.join(row) + ' |' for row in rows[1:])
    return '\n'.join(output)


def render_docx(source: Path, root: Path) -> str:
    with zipfile.ZipFile(source) as archive:
        document = ET.fromstring(archive.read('word/document.xml'))
        rels = {}
        if 'word/_rels/document.xml.rels' in archive.namelist():
            rels = {r.attrib['Id']: r.attrib['Target']
                    for r in ET.fromstring(archive.read('word/_rels/document.xml.rels'))}
        for feature in ('drawing', 'pict', 'object', 'altChunk', 'sdt', 'ins', 'del',
                        'footnoteReference', 'endnoteReference', 'fldChar', 'fldSimple',
                        'numPr', 'vMerge', 'sym', 'txbxContent'):
            if document.find('.//w:' + feature, NS) is not None:
                raise UnsupportedContent(f'{source.name}: unsupported {feature}; extend and review the converter')
        for span in document.findall('.//w:gridSpan', NS):
            if span.get(tag('val'), '1') != '1':
                raise UnsupportedContent(f'{source.name}: merged table cells')
        body = document.find('w:body', NS)
        if body is None:
            raise UnsupportedContent('Missing document body')
        blocks = []
        for child in body:
            if child.tag == tag('p'):
                block = paragraph(child, rels)
            elif child.tag == tag('tbl'):
                if child.find('.//w:tbl', NS) is not None:
                    raise UnsupportedContent('Nested table')
                block = table(child, rels)
            elif child.tag == tag('sectPr'):
                continue
            else:
                raise UnsupportedContent(f'Unsupported body element: {child.tag}')
            if block:
                blocks.append(block)
    if not blocks or not blocks[0].startswith('# '):
        raise UnsupportedContent(f'{source.name}: expected a Word Title paragraph first')
    rel = source.relative_to(root).as_posix()
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    header = f'{MARKER}source={rel}; sha256={digest} -->'
    notice = (f'> [Download the Word version]({quote(source.name)}) · '
              'This Markdown copy is generated from the DOCX. Update the DOCX, then run '
              '`python scripts/sync_documents.py --write` from the repository root. '
              'Print layout, page breaks, headers/footers, and writing-space height remain in Word.')
    return header + '\n\n' + blocks[0] + '\n\n' + notice + '\n\n' + '\n\n'.join(blocks[1:]) + '\n'


def visible_files(root: Path, pattern: str):
    return sorted(p for p in root.rglob(pattern)
                  if not any(part.startswith('.') for part in p.relative_to(root).parts)
                  and not p.name.startswith('~$'))


def sync(root: Path, write: bool) -> int:
    sources = visible_files(root, '*.docx')
    if not sources:
        raise ValueError('No DOCX documents found')
    # Validate every conversion before writing any file.
    outputs = [(p.with_suffix('.md'), render_docx(p, root)) for p in sources]
    targets = {p for p, _ in outputs}
    problems = []
    for md in visible_files(root, '*.md'):
        if md not in targets and md.read_text(encoding='utf-8-sig').startswith(MARKER):
            problems.append(f'Orphan generated mirror (source missing): {md.relative_to(root)}')
    for target, expected in outputs:
        actual = target.read_text(encoding='utf-8-sig') if target.exists() else None
        if actual is not None and not actual.startswith(MARKER):
            raise ValueError(f'Refusing to overwrite an independently authored file: {target}')
        if actual != expected:
            if write:
                target.write_text(expected, encoding='utf-8', newline='\n')
                print('Updated ' + target.relative_to(root).as_posix())
            else:
                problems.append('Missing or stale mirror: ' + target.relative_to(root).as_posix())
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print('Update DOCX sources as needed, then run: python scripts/sync_documents.py --write', file=sys.stderr)
        return 1
    print(f'{len(outputs)} DOCX/Markdown pairs are in sync.')
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true', help='Regenerate Markdown from DOCX sources')
    mode.add_argument('--check', action='store_true', help='Fail if any mirror is missing, stale, or orphaned')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    try:
        return sync(args.root.resolve(), args.write)
    except (UnsupportedContent, ValueError, KeyError, ET.ParseError, zipfile.BadZipFile) as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
